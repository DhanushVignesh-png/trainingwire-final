// FILE: api/src/functions/activity.js
// Training Wire — POST /api/activity
//
// Headline Activity, shared. Who did what to a release — entered it, filed a
// snap, flagged coverage, corrected, withdrew. Previously this lived only in
// the browser that did the action, so nobody else saw it. Now every entry is
// stored and broadcast, so the whole cohort sees one activity feed per release.
//
// Entries are broadcast individually (like publish) rather than re-pushing the
// whole feed, to keep the free-tier bandwidth down with 20 trainees.
//
// Body: { release, what }
//   release — the release id (partition key for its activity)
//   what    — plain text describing the action (HTML is escaped on the client)
//
// NOTE: the "what" string may contain the small inline markup the client uses
// (act-kw / act-flag / act-wd spans). It is NOT user-free-text in the sense of
// a release body — it is generated by the client from fixed templates — but we
// still cap its length and never put it near innerHTML without the client's own
// escaping of the embedded values.
'use strict';

const { app } = require('@azure/functions');
const { WebPubSubServiceClient } = require('@azure/web-pubsub');
const crypto = require('crypto');
const { ENV, TABLES, WIRE_GROUP, requireEnv } = require('../shared/config');
const { getSession, json } = require('../shared/auth');
const tables = require('../shared/tables');

const ACTIVITY_TABLE = 'activity';
const MAX_WHAT = 600;

app.http('activity', {
  methods: ['POST'],
  authLevel: 'anonymous',
  route: 'activity',
  handler: async (request, context) => {
    const session = getSession(request);
    if (!session) return json(401, { error: 'Unauthorized.' });
    const who = session.name || session.sub;

    let body;
    try { body = await request.json(); } catch (e) { return json(400, { error: 'Invalid JSON body.' }); }

    const release = String((body && body.release) || '').trim();
    let what = String((body && body.what) || '').trim();

    if (!release) return json(400, { error: 'A release is required.' });
    if (!what) return json(400, { error: 'An activity description is required.' });
    if (what.length > MAX_WHAT) what = what.slice(0, MAX_WHAT);

    const now = Date.now();
    const id = crypto.randomUUID();
    const rowKey = String(now) + '-' + id;

    try {
      await tables.upsert(ACTIVITY_TABLE, {
        partitionKey: release,
        rowKey,
        id,
        release,
        who,
        what,
        createdAt: now,
      });
    } catch (e) {
      context.error('activity store failed: ' + (e && e.message));
      return json(500, { error: 'Could not record the activity.' });
    }

    try {
      requireEnv(['WPS_CONNECTION', 'WPS_HUB']);
      const service = new WebPubSubServiceClient(ENV.WPS_CONNECTION, ENV.WPS_HUB);
      await service.group(WIRE_GROUP).sendToAll({
        type: 'activity',
        payload: { release, id, who, what, createdAt: now },
      });
    } catch (e) {
      context.error('activity broadcast failed: ' + (e && e.message));
    }

    return json(200, { ok: true, release, id, who, what, createdAt: now });
  },
});
